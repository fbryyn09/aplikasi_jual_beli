class Product {
  final int id;
  final String nama;
  final int harga;
  final String emoji;
  final String deskripsi;
  final String kategori;
  final int stok;

  Product({
    required this.id,
    required this.nama,
    required this.harga,
    required this.emoji,
    required this.deskripsi,
    required this.kategori,
    required this.stok,
  });
}